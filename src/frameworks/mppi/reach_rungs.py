"""v2.8.4 — the reach LADDER for the (T, omega_des) cascade. One flag per rung, every OFF state
bit-parity with the shipped implementation.

SUBJECT. `src/frameworks/mppi/cascade_rate.py`. That file is NOT MODIFIED BY THIS WORK — every rung lives
in the subclass below, so "existing default behaviour unchanged" is structural rather than asserted.
`cascade.py` (the v5 a_des plan) is not the subject and is not imported.

WHAT IS NOT TOUCHED, ANYWHERE IN THIS MODULE
--------------------------------------------
  * the interface: the planner samples v = [T, w_x, w_y, w_z] and nothing else;
  * the inner rate loop `tau = J k_rate (omega_des - omega)` — `RateCascadeController.inner_loop`, CALLED;
  * the post-allocation per-rotor clip — inside `MPPIController.allocate`, CALLED;
  * the full RK4 rotor-thrust SIMULATION plant — `src.common.rk4.rk4_step` on `system`, CALLED;
  * the collision predicate `cost.collision_mask` and the cost's collision term `C_crash * 1{collided}`;
  * the min-cost baseline subtraction, the ESS definition, the degenerate rule, the control hold, the
    receding-horizon shift, the hover centring and the OU sampler.

There is NO reference trajectory, NO global planner and NO map in this file. The one asymmetry any rung
receives is named at its point of use (see R2).

THE OFF-STATE GUARANTEE
-----------------------
`ReachCascadeController.act` dispatches to `super().act` — the shipped `RateCascadeController.act` — the
instant `ReachFlags.any_on` is false. No rung branch is entered, no extra draw is taken from the
generator and no tensor is formed, so the OFF state is the shipped code path itself, not a copy of it.
The parity is nevertheless MEASURED (see `reach_ladder.py`, the `all_flags_off` rung) rather than left as
an argument.

THE RUNGS
---------
R1  `r1_lambda`      the relative-lambda rule's spread estimator. Shipped: `lam * cost.std()` over the K
                     sample costs (`cascade_rate.py:699-702`). R0 measured that std to be dominated by a
                     ~3 % tail of samples charged C_crash for leaving the vertical band, which is why the
                     shipped rule resolves lambda p50 467 and ESS p50 847. "quantile" replaces the
                     estimator by the spread of the SHIFTED cost below a quantile,
                     `lam * (quantile_q(C) - min_k C)`, which the C_crash tail cannot move. The min-cost
                     baseline is unchanged — it is already subtracted at `cascade_rate.py:692`.

R2  `r2_n_seed`      GMPPI's seeded deterministic rollouts (arXiv:2510.12924; the mission's R2, which
                     states the construction: "K_seed of K rollouts generated by the deployed
                     deterministic cascade with per-rollout perturbed gains, the rest sampled as now").
                     The first `r2_n_seed` rows of the sample block are replaced by (T, omega) sequences
                     produced by rolling `smoke_cascade_rate.shipped_pd_command` forward IN THE PLANNER'S
                     OWN MODEL, with per-rollout multiplicative jitter on the three gains it reads off the
                     system object. Row 0 carries the UNJITTERED deployed law. Everything downstream is
                     unchanged: the same cost scores them, the same weights combine them, and because
                     `update = plan + sum_k w_k (sampled_k - base)` the updated nominal is exactly the
                     weighted average of the sampled sequences — which is the form GMPPI's Eq. 3 uses.

                     ASYMMETRY, NAMED AT THE POINT OF USE: the deterministic law reads the GOAL and the
                     STATE only (`a_des = -kp_pos (p - g) - kd_pos v`, all gains read off the system
                     object). It is a feedback law, not a reference trajectory, not a global plan and not
                     a map, and it is available to the baseline for the same reason the goal is.

R3  `r3_yaw`         the yaw channel is not sampled. "damped" sets w_z of every sampled sequence to
                     `-k_yaw * yaw(q)` — a proportional law on the vehicle's OWN yaw, read from the state
                     through the shipped quaternion-to-rotation map, with no reference of any kind — so
                     the sampling space loses one dimension.

R4  `r4_edge`        rollout-index-dependent noise. The drawn perturbation is scaled along the horizon
                     by `edge + (1 - edge) * sin(pi (j + 1/2) / H)`: smaller at the start and the end of
                     the rollout, larger in the middle. `edge = 1.0` is the uniform shipped profile, i.e.
                     OFF.

R5                   NOT IMPLEMENTED. A graded obstacle cost scaled by (N - j) in place of the binary
                     indicator is a change to THE COST'S COLLISION TERM, which the mission puts behind a
                     stop-and-ask. See `docs/versions/v2.8.4/mppi_reach.md`.

R6  `r6_dt_growth`   dynamic rollout timesteps: physical step j of the rollout is integrated for
                     `dt_j = dt * g^j`, renormalised so `sum_j dt_j == H * dt` exactly, so the horizon
                     covers more distance at the same step count without lengthening it in time-integral
                     terms. `g = 1.0` is the uniform shipped schedule, i.e. OFF. The SIMULATION plant's
                     step is untouched — this is the planner's rollout only.

Every constant is read from the system object or the config. Nothing is typed.
"""

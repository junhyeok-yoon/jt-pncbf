# the deterministic sequence, rolled in THE PLANNER'S OWN MODEL
# =================================================================================================
@torch.no_grad()
def deterministic_sequence(
    system: System, controller: RateCascadeController, x: Tensor, goal: Tensor, horizon: int
) -> Tensor:
    """The (T, omega_des) sequence the SHIPPED deterministic law would command over one horizon, rolled
    forward in `_RatePlannerModel` — the planner's own model, the same one every sampled rollout uses.

    `smoke_cascade_rate.shipped_pd_command` is CALLED, not re-implemented: it is `System.lqr_action`'s own
    outer loop written in this interface, and `smoke.json` check (f) records it reproducing
    `system.lqr_action` to 0.0 N. The planner's `rate_limit` and the planner's low-pass are applied
    exactly as `cascade_rate.py:610` and `:672-673` apply them, so the result is an admissible plan in the
    space the sampler searches — nothing more.

    ASYMMETRY, NAMED HERE AT THE POINT OF USE: the law reads the GOAL and the STATE only. It is not a
    reference trajectory, not a global planner and not a map.

    Returns [H, 4].
    """
    beta = controller.lowpass_beta
    state = x.clone()
    rate_f = state[:, _W].clone()
    entries = []
    for _ in range(horizon):
        thrust, omega_des = smoke.shipped_pd_command(system, state, goal)
        command = controller.rate_limit(torch.cat([thrust, omega_des], dim=-1))     # [1,4]
        entries.append(command[0].clone())
        rate_f = beta * rate_f + (1.0 - beta) * command[:, 1:]
        state = torch.cat([state[:, :10], rate_f], dim=1)
        state = rk4_step(controller.planner, state, command, controller.dt)
    return torch.stack(entries, dim=0)



# N2 — where the collision charge on an obstacle-free scene comes from
# =================================================================================================
@torch.no_grad()
def band_attribution(
    system: System, controller: RateCascadeController, x: Tensor, sampled: Tensor,
    centers: Tensor, radii: Tensor, active: Tensor,
) -> dict[str, float]:
    """Re-roll the drawn samples through the PLANNER'S model, applying the SAME `collision_mask` the
    rollout charges C_crash with, and record what fraction of samples are charged, at which horizon index
    the first charge lands and how far in |z| the samples travel. `sampled` is [N, H, 4].

    The obstacle leg is evaluated too and reported separately, so "the charge is the band" is measured
    rather than asserted: on this scene the single obstacle slot is inactive.
    """
    n, horizon, _ = sampled.shape
    beta = controller.lowpass_beta
    state = x.expand(n, -1).clone()
    rate_f = state[:, _W].clone()
    dead = torch.zeros(n, dtype=torch.bool, device=controller.device)
    first_index = torch.full((n,), -1, dtype=torch.long, device=controller.device)
    max_abs_z = torch.zeros(n, dtype=controller.dtype, device=controller.device)
    obstacle_hits = torch.zeros(n, dtype=torch.bool, device=controller.device)
    for k in range(horizon):
        command = sampled[:, k]
        rate_f = beta * rate_f + (1.0 - beta) * command[:, 1:]
        state = torch.cat([state[:, :10], rate_f], dim=1)
        nxt = rk4_step(controller.planner, state, command, controller.dt)
        state = torch.where(dead.unsqueeze(-1), state, nxt)
        position = system.position(state).view(1, n, -1)
        collided = collision_mask(position, centers, radii, active, controller.cost).reshape(n)
        # the OBSTACLE leg alone, so the band's contribution is isolated by difference
        pos_o = position[..., : centers.shape[-1]]
        distance = torch.linalg.norm(pos_o.unsqueeze(-2) - centers.unsqueeze(-3), dim=-1)
        obstacle = ((distance < radii.unsqueeze(-2)) & active.unsqueeze(-2)).any(dim=-1).reshape(n)
        obstacle_hits = obstacle_hits | obstacle
        newly = collided & ~dead
        first_index = torch.where(newly, torch.full_like(first_index, k), first_index)
        dead = dead | collided
        max_abs_z = torch.maximum(max_abs_z, system.position(state)[:, 2].abs())
    charged = first_index >= 0
    idx = first_index[charged].to(controller.dtype)
    return {
        "frac_samples_charged": float(charged.double().mean().item()),
        "frac_samples_charged_by_obstacle_leg": float(obstacle_hits.double().mean().item()),
        "first_charge_horizon_index_p50": float(idx.median().item()) if bool(charged.any()) else -1.0,
        "first_charge_horizon_index_min": float(idx.min().item()) if bool(charged.any()) else -1.0,
        "max_abs_z_p50_m": float(max_abs_z.median().item()),
        "max_abs_z_p95_m": float(max_abs_z.quantile(0.95).item()),
        "max_abs_z_max_m": float(max_abs_z.max().item()),
    }


